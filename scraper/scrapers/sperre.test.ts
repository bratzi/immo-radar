import { describe, it, expect } from "vitest";
import {
  erkenneSperre,
  naechsterVersuch,
  SEITENABSTAND_MIN_MS,
  SEITENABSTAND_MAX_MS,
  MAX_LISTENSEITEN,
  MAX_DETAILSEITEN,
  type Sperre,
} from "./sperre.js";

const NORMAL = "<html><head><title>Wohnung mieten München</title></head><body><h1>123 Wohnungen</h1></body></html>";
const URL_OK = "https://www.immowelt.de/classified-search?locations=AD08DE8634";

describe("erkenneSperre", () => {
  const faelle: Array<[string, { status: number; html: string; url: string }, Sperre | null]> = [
    ["normale Ergebnisseite", { status: 200, html: NORMAL, url: URL_OK }, null],
    ["Weiterleitung 304 ohne Inhalt ist keine Sperre", { status: 304, html: "", url: URL_OK }, null],
    ["404 ist keine Sperre (Anzeige weg)", { status: 404, html: "<h1>Seite nicht gefunden</h1>", url: URL_OK }, null],
    ["401 ohne Herstellermerkmal", { status: 401, html: "Unauthorized", url: URL_OK }, "http"],
    ["403 ohne Herstellermerkmal", { status: 403, html: "Forbidden", url: URL_OK }, "http"],
    ["429 Rate-Limit", { status: 429, html: "Too Many Requests", url: URL_OK }, "http"],
    ["DataDome-Challenge im HTML", { status: 403, html: '<script src="https://ct.captcha-delivery.com/c.js"></script><p>datadome</p>', url: URL_OK }, "datadome"],
    ["DataDome auch bei 200", { status: 200, html: "<script>var dd={'cid':'x','hsh':'y'}</script><script src=\"https://geo.captcha-delivery.com/captcha/\"></script>", url: URL_OK }, "datadome"],
    ["DataDome-URL nach Weiterleitung", { status: 200, html: "<html></html>", url: "https://geo.captcha-delivery.com/captcha/?initialCid=x" }, "datadome"],
    ["Akamai Access Denied", { status: 403, html: "<H1>Access Denied</H1>You don't have permission to access ... Reference&#32;&#35;18.abc", url: URL_OK }, "akamai"],
    ["Akamai Bot-Manager-Challenge", { status: 200, html: '<script src="/_sec/cp_challenge/ak-challenge-3-6.js"></script>', url: URL_OK }, "akamai"],
    ["AWS WAF Challenge", { status: 202, html: '<script src="https://abc.token.awswaf.com/abc/challenge.js"></script>', url: URL_OK }, "waf"],
    ["CloudFront-Block", { status: 403, html: "<H1>403 ERROR</H1><H2>The request could not be satisfied.</H2>Request blocked. Generated by cloudfront (CloudFront)", url: URL_OK }, "waf"],
    ["reCAPTCHA-Seite", { status: 200, html: '<div class="g-recaptcha" data-sitekey="k"></div>', url: URL_OK }, "captcha"],
    ["hCaptcha-Seite", { status: 200, html: '<div class="h-captcha" data-sitekey="k"></div>', url: URL_OK }, "captcha"],
    ["Titel nennt Captcha", { status: 200, html: "<title>Sicherheitsabfrage - Captcha</title>", url: URL_OK }, "captcha"],
    ["Wort recaptcha im Fliesstext ohne Formular ist keine Sperre", { status: 200, html: "<p>Kein recaptcha-Formular, nur Text ueber Bots.</p>", url: URL_OK }, null],
  ];
  for (const [name, eingabe, erwartet] of faelle) {
    it(name, () => expect(erkenneSperre(eingabe)).toBe(erwartet));
  }
});

describe("naechsterVersuch", () => {
  const JETZT = new Date("2026-11-11T12:00:00Z"); // 13:00 in Muenchen (Winterzeit)

  it("ohne Sperre sofort", () => {
    expect(naechsterVersuch(0, JETZT)).toBeNull();
  });
  it("erste Sperre: 2 h Pause", () => {
    expect(naechsterVersuch(1, JETZT)?.toISOString()).toBe("2026-11-11T14:00:00.000Z");
  });
  it("zweite Sperre in Folge: 6 h Pause", () => {
    expect(naechsterVersuch(2, JETZT)?.toISOString()).toBe("2026-11-11T18:00:00.000Z");
  });
  it("dritte Sperre in Folge: naechster Tag 0 Uhr Muenchner Zeit (Winter)", () => {
    expect(naechsterVersuch(3, JETZT)?.toISOString()).toBe("2026-11-11T23:00:00.000Z");
  });
  it("auch spaeter Abend: naechster Tag, nicht derselbe", () => {
    // 23:30 UTC = 00:30 am 12.11. in Muenchen -> naechster Tag ist der 13.11.
    expect(naechsterVersuch(4, new Date("2026-11-11T23:30:00Z"))?.toISOString()).toBe("2026-11-12T23:00:00.000Z");
  });
  it("Sommerzeit: Mitternacht ist 22:00 UTC", () => {
    expect(naechsterVersuch(3, new Date("2026-07-01T10:00:00Z"))?.toISOString()).toBe("2026-07-01T22:00:00.000Z");
  });
});

describe("Drossel-Konstanten", () => {
  it("4 bis 8 s je Seite, hoechstens 5 Listen- und 15 Detailseiten", () => {
    expect(SEITENABSTAND_MIN_MS).toBe(4000);
    expect(SEITENABSTAND_MAX_MS).toBe(8000);
    expect(MAX_LISTENSEITEN).toBe(5);
    expect(MAX_DETAILSEITEN).toBe(15);
  });
});
